"""Literal filesystem paths for read-only SQLite connections."""

from pathlib import Path
from urllib.parse import urlsplit


def readonly_uri(path: Path) -> str:
    """Encode an absolute path without resolving symlinks or losing UNC hosts.

    SQLite rejects most URI authorities and discards ``localhost``. Keep
    every UNC host in the double-slash path instead. Only parse the URI
    generated by pathlib; this function does not accept URI strings.
    """
    if not isinstance(path, Path):
        raise TypeError("expected an absolute filesystem path")
    return _readonly_uri_from_path_uri(path.as_uri())  # Also rejects relative paths.


def _readonly_uri_from_path_uri(uri: str) -> str:
    """Format only a generated Path.as_uri() result, not a general input URI.

    Kept separate so other-platform representations can be tested without
    calling the deprecated PurePath.as_uri(). Production uses readonly_uri.
    """
    parts = urlsplit(uri)
    if parts.scheme != "file" or parts.query or parts.fragment or not parts.path.startswith("/"):
        raise ValueError("expected an absolute Path.as_uri() result")
    if parts.netloc:
        uri = "file:////" + parts.netloc + parts.path
    return uri + "?mode=ro"
